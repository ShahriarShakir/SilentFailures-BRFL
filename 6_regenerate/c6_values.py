#!/usr/bin/env python3
"""Emit the fault-injection numbers as LaTeX macros."""
import json
d = json.load(open("../5_derived_results/c6_injection.json"))
faults = {k: v for k, v in d.items() if v["kind"] == "fault"}
healthy = {k: v for k, v in d.items() if v["kind"] == "healthy"}
beh = lambda v: [x for x in ("T1", "T2", "T4", "T5") if v["checks"].get(x) is True]   # behavioural checks only
probe = {k: v for k, v in d.items() if v["kind"] == "probe"}
fires = lambda t: sum(1 for v in faults.values() if v["checks"].get(t) is True)
M = {
 "CSixNFault": len(faults), "CSixNHealthy": len(healthy),
 "CSixCaught": sum(1 for v in faults.values() if beh(v)),
 "CSixMissed": sum(1 for v in faults.values() if not beh(v)),
 "CSixFalseAlarm": sum(1 for v in healthy.values() if beh(v)),
 "CSixTThreeFires": sum(1 for v in d.values() if v["checks"].get("T3") is True),
 "CSixTTwoFires": fires("T2"), "CSixTFiveFires": fires("T5"),
 "CSixTFiveWeakFires": sum(1 for v in faults.values() if v["checks"].get("T5_input_varies") is True),
 "CSixNProbe": len(probe),
 "CSixN": len(d),
 "CSixHealthyG": f"{healthy['healthy']['global_last3']:.3f}",
 "CSixHealthyL": f"{healthy['healthy']['local_last3']:.3f}",
 "CSixBufG": f"{faults['buffers not shared']['global_last3']:.3f}",
 "CSixBufL": f"{faults['buffers not shared']['local_last3']:.3f}",
}
import sys as _sys, numpy as _np
_sys.path.insert(0, "../3_tests/fault_injection")
from inject import make_clients as _mk
_cl = _mk(6, 256, 10, 7)                        # K, n, classes, data seed, as in inject.run
_v = _np.array([float(x.mean()) + (3.0 if k < 2 else 0.0) for k, (x, y) in enumerate(_cl)])   # two attackers, +3.0 shift
_med = _np.median(_v); _mad = max(float(_np.median(_np.abs(_v - _med))) * 1.4826, 1e-9); _z = _np.abs(_v - _med) / _mad
M.update({"CSixProbeZLo": f"{min(_z[:2]):.1f}", "CSixProbeZHi": f"{max(_z[:2]):.1f}", "CSixProbeZHon": f"{max(_z[2:]):.2f}"})
REPL = "../5_derived_results/c6_replication.json"
# ---- Replication (Section 9, Appendix G): further replicates, each with a new data draw and new
# training seeds, run on CPU; client-local metric also on a held-out split of each client's own data
import os as _os
_R = json.load(open(REPL))
_reps = sorted(_R, key=int)
_bset = lambda c: tuple(x for x in ("T1", "T2", "T4", "T5") if c.get(x) is True)
_conds = lambda r: _R[r]["conditions"]
_caught = lambda r: sum(1 for k, v in _conds(r).items() if v["kind"] == "fault" and _bset(v["checks"]))
_false = lambda r: sum(1 for k, v in _conds(r).items() if v["kind"] == "healthy" and _bset(v["checks"]))
_same = sum(1 for r in _reps if all(_bset(_conds(r)[k]["checks"]) == tuple(beh(v)) for k, v in d.items()))
_t4a_ok = sum(1 for r in _reps if [k for k, v in _conds(r).items() if v["checks"]["T4_assert"]] == ["seed ignored"])
_t4t = sum(1 for r in _reps for v in _conds(r).values() if v["checks"]["T4_trajectory"])
_runs = lambda name, key: _np.array([x for r in _reps for x in _conds(r)[name][key]])
_H, _B = "healthy", "buffers not shared"
_dg = _runs(_H, "global_last3") - _runs(_B, "global_last3")
_dv = _runs(_H, "local_val_last3") - _runs(_B, "local_val_last3")
_dt = _runs(_H, "local_train_last3") - _runs(_B, "local_train_last3")
f3 = lambda x: f"{x:.3f}"
M.update({"CSixRepN": len(_reps), "CSixRepRuns": len(_dg), "CSixRepSame": _same,
          "CSixRepCaughtMin": min(map(_caught, _reps)), "CSixRepCaughtMax": max(map(_caught, _reps)),
          "CSixRepFalseMin": min(map(_false, _reps)), "CSixRepFalseMax": max(map(_false, _reps)),
          "CSixRepTFourAssertOK": _t4a_ok, "CSixRepTFourTrajFires": _t4t,
          "CSixRepNegRuns": int((_dg < 0).sum()), "CSixRepFalseRepl": sum(1 for r in _reps if _false(r)),
          "CSixRepHealthyG": f3(_runs(_H, "global_last3").mean()), "CSixRepHealthyGSD": f3(_runs(_H, "global_last3").std(ddof=1)),
          "CSixRepBufG": f3(_runs(_B, "global_last3").mean()), "CSixRepBufGSD": f3(_runs(_B, "global_last3").std(ddof=1)),
          "CSixRepHealthyLV": f3(_runs(_H, "local_val_last3").mean()), "CSixRepBufLV": f3(_runs(_B, "local_val_last3").mean()),
          "CSixRepDiffG": f3(_dg.mean()), "CSixRepDiffGSD": f3(_dg.std(ddof=1)),
          "CSixRepDiffGMin": f3(_dg.min()),
          "CSixRepDiffLV": f"{_dv.mean():+.3f}", "CSixRepDiffLVSD": f3(_dv.std(ddof=1)),
          "CSixRepDiffLVMax": f3(_np.abs(_dv).max()), "CSixRepDiffLTMax": f3(_np.abs(_dt).max())})
_rows = []
for r in _reps:
    c = _conds(r); m = lambda name, key: f3(_np.mean(c[name][key]))
    _rows.append(f"{r} & {m(_H, 'global_last3')} & {m(_B, 'global_last3')} & {m(_H, 'local_train_last3')} & "
                 f"{m(_B, 'local_train_last3')} & {m(_H, 'local_val_last3')} & {m(_B, 'local_val_last3')} & "
                 f"{_caught(r)} & {_false(r)} \\\\")
M["CSixRepRows"] = " ".join(_rows)
with open("./c6_values.tex", "w") as f:
    f.write("% AUTO-GENERATED by figures/c6_values.py\n")
    for k, v in M.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
for k, v in M.items(): print(f"  {k:18s} {v}")
