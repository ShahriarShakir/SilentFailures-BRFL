#!/usr/bin/env python3
"""Emit the fault-injection numbers as LaTeX macros."""
import json
d = json.load(open("../5_derived_results/c6_injection.json"))
faults = {k: v for k, v in d.items() if v["kind"] == "fault"}
healthy = {k: v for k, v in d.items() if v["kind"] == "healthy"}
beh = lambda v: [x for x in ("T1", "T2", "T4", "T5") if v["checks"].get(x) is True]   # behavioural checks only
probe = {k: v for k, v in d.items() if v["kind"] == "probe"}
fires = lambda t: sum(1 for v in faults.values() if v["checks"].get(t) is True)
M = {
 "CSixNFault": len(faults), "CSixNHealthy": len(healthy),
 "CSixCaught": sum(1 for v in faults.values() if beh(v)),
 "CSixMissed": sum(1 for v in faults.values() if not beh(v)),
 "CSixFalseAlarm": sum(1 for v in healthy.values() if beh(v)),
 "CSixTThreeFires": sum(1 for v in d.values() if v["checks"].get("T3") is True),
 "CSixTTwoFires": fires("T2"), "CSixTFiveFires": fires("T5"),
 "CSixTFiveWeakFires": sum(1 for v in faults.values() if v["checks"].get("T5_input_varies") is True),
 "CSixNProbe": len(probe),
 "CSixN": len(d),
 "CSixHealthyG": f"{healthy['healthy']['global_last3']:.3f}",
 "CSixHealthyL": f"{healthy['healthy']['local_last3']:.3f}",
 "CSixBufG": f"{faults['buffers not shared']['global_last3']:.3f}",
 "CSixBufL": f"{faults['buffers not shared']['local_last3']:.3f}",
}
import sys as _sys, numpy as _np
_sys.path.insert(0, "../3_tests/fault_injection")
from inject import make_clients as _mk
_cl = _mk(6, 256, 10, 7)                        # K, n, classes, data seed, as in inject.run
_v = _np.array([float(x.mean()) + (3.0 if k < 2 else 0.0) for k, (x, y) in enumerate(_cl)])   # two attackers, +3.0 shift
_med = _np.median(_v); _mad = max(float(_np.median(_np.abs(_v - _med))) * 1.4826, 1e-9); _z = _np.abs(_v - _med) / _mad
M.update({"CSixProbeZLo": f"{min(_z[:2]):.1f}", "CSixProbeZHi": f"{max(_z[:2]):.1f}", "CSixProbeZHon": f"{max(_z[2:]):.2f}"})
with open("./c6_values.tex", "w") as f:
    f.write("% AUTO-GENERATED by figures/c6_values.py\n")
    for k, v in M.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
for k, v in M.items(): print(f"  {k:18s} {v}")
